/**
 * Generates local placeholder imagery so the design can be reviewed before the DJs
 * supply photos. Gradients (not flat grey) are used deliberately: they exercise
 * text-over-image contrast and focal points the way real photos will.
 *
 * These are never shippable. Real photos must replace them before launch.
 * Run: node scripts/generate-placeholders.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const OUT_DIR = join(process.cwd(), 'public', 'placeholders');

const PALETTES = [
  ['#2b1b4d', '#7b2d6b', '#c2543f'],
  ['#10233f', '#1f5f7a', '#4bb3a5'],
  ['#3d1330', '#8a2246', '#e0654f'],
  ['#161a3a', '#3b3f8f', '#8f6fd0'],
  ['#2a1408', '#7a3b12', '#d9913a'],
  ['#0d2a2a', '#1d5c4f', '#7fbf6a'],
];

function svg(width, height, label, paletteIndex) {
  const [a, b, c] = PALETTES[paletteIndex % PALETTES.length];
  const id = `g${paletteIndex}`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${label}">
  <defs>
    <linearGradient id="${id}" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="${a}"/>
      <stop offset="55%" stop-color="${b}"/>
      <stop offset="100%" stop-color="${c}"/>
    </linearGradient>
    <radialGradient id="${id}s" cx="0.7" cy="0.25" r="0.8">
      <stop offset="0%" stop-color="#ffffff" stop-opacity="0.35"/>
      <stop offset="100%" stop-color="#ffffff" stop-opacity="0"/>
    </radialGradient>
    <filter id="${id}n">
      <feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="3"/>
      <feColorMatrix type="saturate" values="0"/>
    </filter>
  </defs>
  <rect width="${width}" height="${height}" fill="url(#${id})"/>
  <rect width="${width}" height="${height}" fill="url(#${id}s)"/>
  <rect width="${width}" height="${height}" filter="url(#${id}n)" opacity="0.12"/>
  <rect x="0" y="${height * 0.55}" width="${width}" height="${height * 0.45}" fill="#000000" opacity="0.35"/>
  <text x="${width / 2}" y="${height / 2}" fill="#ffffff" fill-opacity="0.72"
        font-family="system-ui, sans-serif" font-size="${Math.round(Math.min(width, height) * 0.055)}"
        font-weight="600" text-anchor="middle" letter-spacing="2">PLACEHOLDER</text>
  <text x="${width / 2}" y="${height / 2 + Math.round(Math.min(width, height) * 0.075)}" fill="#ffffff" fill-opacity="0.5"
        font-family="system-ui, sans-serif" font-size="${Math.round(Math.min(width, height) * 0.036)}"
        text-anchor="middle">${label}</text>
</svg>
`;
}

const SERVICES = [
  'weddings',
  'proms',
  'corporate',
  'birthdays',
  'anniversaries',
  'christenings',
];

await mkdir(OUT_DIR, { recursive: true });

const written = [];

await writeFile(join(OUT_DIR, 'hero.svg'), svg(1920, 1080, 'hero', 0), 'utf8');
written.push('hero.svg');

for (const [index, name] of SERVICES.entries()) {
  const file = `${name}.svg`;
  await writeFile(join(OUT_DIR, file), svg(1200, 800, name, index), 'utf8');
  written.push(file);
}

for (let index = 0; index < 12; index += 1) {
  const portrait = index % 3 === 1;
  const file = `gallery-${index + 1}.svg`;
  await writeFile(
    join(OUT_DIR, file),
    svg(portrait ? 800 : 1200, portrait ? 1200 : 800, `gallery ${index + 1}`, index),
    'utf8'
  );
  written.push(file);
}

await writeFile(
  join(OUT_DIR, 'README.md'),
  '# Placeholder imagery\n\nGenerated by `scripts/generate-placeholders.mjs`.\n\n' +
    'These are development stand-ins only. Every file here must be replaced with the\n' +
    "DJs' own event photography before launch. Do not substitute stock photos of other\n" +
    "people's events — presenting them as your own work is deceptive and a real\n" +
    'reputational risk for a wedding vendor.\n',
  'utf8'
);

console.log(`Generated ${written.length} placeholder files in public/placeholders/`);
